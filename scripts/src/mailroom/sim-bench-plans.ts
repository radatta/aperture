// The sim bench's plans (docs/ops/SIM-BENCH.md): ios-standalone's own jobs, recorded by devcheck/ios-plans.ts, so the
// bench on a Mac replays exactly the jobs a devcheck sends. A step's API writes before its job are setup the bench skips, and
// the MCP writes (the Done form's in-progress task) become the seed `pnpm sim-bench:seed` creates. Writes
// tools/mailroom/bench/plans.json; sim-bench-plans.test.ts fails when the committed file drifts from this.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { recordIosPlans } from '../devcheck/ios-plans';
import { iosStandalone } from '../devcheck/scenarios/ios-standalone';
import { DEFAULT_TIMEOUT_SEC } from '../devcheck/ios';
import { TOOLS_DIR } from './fixtures.ts';
import type { IosOp } from './sim.ts';

export const PLANS_PATH = `${TOOLS_DIR}bench/plans.json`;
export const BENCH_NONCE = 'simbench';
export const PRELUDE_TIMEOUT_SEC = 600;
// Sign-in apart from the timed runs, ending off: every run then starts from a shut-down sim, as relaunch (the last job) leaves it.
export const PRELUDE: IosOp[] = [
  { op: 'launch' },
  { op: 'signIn' },
  { op: 'expect', signedIn: true },
  { op: 'shutdown' },
];

export interface BenchJob {
  name: string;
  step: string; // the scenario step that sends it
  steps: IosOp[];
  skippedSetup?: string[]; // API writes the step makes before the job, which the bench doesn't (e.g. capture-long's padding)
}
export interface BenchSeed {
  title: string;
  estimateMin: number | null;
  status: string;
}
export interface BenchPlans {
  about: string;
  scenario: string;
  nonce: string;
  timeoutSec: number;
  prelude: { name: 'prelude'; timeoutSec: number; steps: IosOp[] };
  seed: BenchSeed;
  jobs: BenchJob[];
}

export async function exportPlans(): Promise<BenchPlans> {
  const seeds: BenchSeed[] = [];
  const recorded = await recordIosPlans(iosStandalone, {
    nonce: BENCH_NONCE,
    steps: 'all',
    fakes: ({ count, fakeId }) => ({
      api: {
        reads: {
          getSettings: async () => ({ dayStartHour: 4 }),
          getTask: async () => ({ status: 'in_progress' }),
        },
        writes: {
          createTask: async () => (count('createTask'), { id: fakeId() }),
          upsertPlan: async () => (count('upsertPlan'), {}),
          transitionTask: async () => (count('transitionTask'), {}),
          deleteTask: async () => {}, // the step's own cleanup of what it created
        },
      },
      mcp: {
        writes: {
          createTask: async (input: { title: string; estimateMin?: number }) => {
            seeds.push({
              title: input.title,
              estimateMin: input.estimateMin ?? null,
              status: 'backlog',
            });
            return { id: fakeId() };
          },
          updateTask: async (_id: string, patch: { status?: string }) => {
            const s = seeds.at(-1);
            if (s && patch.status) s.status = patch.status;
            return {};
          },
        },
      },
    }),
  });
  const jobs: BenchJob[] = recorded.map((j) => ({
    name: j.name,
    step: j.step,
    steps: j.steps,
    ...(j.setupWrites.length ? { skippedSetup: summarize(j.setupWrites) } : {}),
  }));
  if (seeds.length !== 1)
    throw new Error(`the scenario set up ${seeds.length} tasks, the bench seeds one`);
  return {
    about:
      'Generated by `pnpm sim-bench:plans` from scripts/src/devcheck/scenarios/ios-standalone.ts — never edit by hand (docs/ops/SIM-BENCH.md).',
    scenario: iosStandalone.id,
    nonce: BENCH_NONCE,
    timeoutSec: DEFAULT_TIMEOUT_SEC,
    prelude: { name: 'prelude', timeoutSec: PRELUDE_TIMEOUT_SEC, steps: PRELUDE },
    seed: seeds[0]!,
    jobs,
  };
}

// ["createTask", "createTask", "upsertPlan"] → ["2 createTask", "1 upsertPlan"], first-seen order.
function summarize(calls: string[]): string[] {
  const n = new Map<string, number>();
  for (const c of calls) n.set(c, (n.get(c) ?? 0) + 1);
  return [...n].map(([c, k]) => `${k} ${c}`);
}

export const render = (p: BenchPlans): string => JSON.stringify(p, null, 2) + '\n';

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  exportPlans().then(
    (p) => {
      writeFileSync(PLANS_PATH, render(p));
      console.log(`wrote ${PLANS_PATH}: ${p.jobs.map((j) => j.name).join(', ')}`);
    },
    (err: unknown) => {
      console.error(err instanceof Error ? err.message : err);
      process.exit(1);
    },
  );
