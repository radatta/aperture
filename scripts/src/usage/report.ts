// The report's text: the same lines go to the terminal and to <usage dir>/report-<day>.md.
import type { FitModel, ReportModel } from './model.ts';

export const f1 = (x: number | null | undefined, d = 1) =>
  x === null || x === undefined || !Number.isFinite(x) ? '–' : x.toFixed(d);
const perPt = (k: number | null | undefined) => (k && k > 0 ? 1 / k : null);
const clock = (ms: number | null) =>
  ms === null
    ? '–'
    : new Date(ms).toLocaleString('en-US', {
        timeZone: 'America/Los_Angeles',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        hour12: false,
      });

export function fitLines(m: FitModel): string[] {
  const out: string[] = ['## k: meter % per QU (1 QU = $1 at API list prices)', ''];
  const a = m.all;
  if (!a.fit) {
    out.push('Not enough data: no interval of 3+ points inside the calls table yet.', '');
  } else {
    const u = a.unc;
    out.push(
      `- **k = ${f1(a.fit.k, 4)} %/QU** (≈ ${f1(perPt(a.fit.k))} QU per point), λ = ${f1(a.fit.lambda, 2)} %/h${a.fit.lambdaFixed ? ' (held at 0: too few intervals or ΔQU and Δt move together)' : ''}, from ${a.fit.n} intervals.`,
      !u || u.method === 'none'
        ? '- No interval: too few intervals to resample.'
        : `- ${u.method === 'bootstrap' ? 'Bootstrap' : 'Leave-one-out range'}: k 80% ${f1(u.k80?.lo, 4)}–${f1(u.k80?.hi, 4)}, 95% ${f1(u.k95?.lo, 4)}–${f1(u.k95?.hi, 4)}${u.zeroShare > 0 ? `; ${f1(u.zeroShare * 100, 0)}% of resamples gave k = 0 (left out of k's spread)` : ''}.`,
      `- With λ = 0 (all movement charged to agent work, the upper bound): k = ${f1(a.kOnly?.k, 4)} (≈ ${f1(perPt(a.kOnly?.k))} QU per point).`,
    );
    if (m.inferredResets.length)
      out.push(
        `- Weekly resets inferred from resets_at and split on: ${m.inferredResets.map((r) => clock(Date.parse(r))).join(', ')} (PT).`,
      );
    const h = m.history;
    if (h.fit)
      out.push(
        `- History only (manual readings, ${h.fit.n} intervals): k = ${f1(h.fit.k, 4)}, λ = ${f1(h.fit.lambda, 2)}.`,
      );
    const ho = m.live.holdout;
    if (ho)
      out.push(
        `- Held-out live ticks (${ho.n} intervals): the history fit predicted ${f1(ho.predicted)} points, actual ${f1(ho.actual)}; MAE ${f1(ho.mae, 2)} points per interval.`,
      );
    if (m.live.logRatio !== null)
      out.push(
        `- Calls table vs the status line's own cost over the live ticks: ${f1(m.live.logRatio, 2)}× (1.0 = additive; over 1 means the status line leaves something out, e.g. subagents).`,
      );
    out.push('');
    out.push('| Interval | ΔP | ΔQU | Δt h | QU/pt | Source |', '|---|---|---|---|---|---|');
    for (const o of [...m.history.obs, ...m.live.obs])
      out.push(
        `| ${clock(o.t0)} → ${clock(o.t1)} | ${f1(o.dP, Number.isInteger(o.dP) ? 0 : 1)} | ${f1(o.dQU)} | ${f1(o.dT, 2)} | ${f1(o.dQU / o.dP)} | ${o.src} |`,
      );
    out.push('');
  }
  const b = m.burn;
  out.push(
    '## Burn now',
    '',
    b.resetAt !== null
      ? `- The meter reset at ${clock(b.resetAt)} (PT) and no session has reported since: no current reading.`
      : `- Meter ${b.pct ?? '–'}% · ${f1(b.pctPerHour, 2)} %/h${b.since !== null ? ` (ticks since ${clock(b.since)})` : ' (from k × QU/h)'} · ${f1(b.quPerHour)} QU in the last hour · ~${f1(b.hoursTo100)} h to 100%.`,
    `- Calls table covers ${clock(m.coverage.from)} → ${clock(m.coverage.to)} (PT); ${m.live.windows} meter window(s) in the log, ${m.live.stragglers} stale readings ignored.`,
    '',
  );
  return out;
}

// One line for a status bar or the tower.
export function boardLine(m: FitModel): string {
  const b = m.burn;
  if (b.resetAt !== null) return `usage reset ${clock(b.resetAt)} · no reading since`;
  if (b.pct === null) return 'usage –';
  const parts = [`usage ${b.pct}%`];
  if (b.pctPerHour) parts.push(`${f1(b.pctPerHour)}%/h`);
  if (b.hoursTo100 !== null) parts.push(`~${f1(b.hoursTo100)} h to 100%`);
  return parts.join(' · ');
}

const pctStr = (x: number | null) =>
  x === null || !Number.isFinite(x) ? '–' : `${x.toFixed(x < 1 ? 2 : 1)}%`;
const qu = (x: number) => (Number.isFinite(x) ? x.toFixed(x < 10 ? 1 : 0) : '–');

export function reportLines(m: ReportModel, now: number): string[] {
  const out: string[] = [
    `# Usage cost model — ${clock(now)} PT`,
    '',
    'Generated by `pnpm usage report` (docs/ops/USAGE-METER.md). QU = list-price USD of the tokens; k turns QU into meter %.',
    '',
    ...fitLines(m.fit),
  ];

  out.push('## Per PR type', '');
  out.push(
    `Log-cost model, ${m.shrinkage ? 'type means shrunk toward the overall mean' : 'no shrinkage (under 3 types with 2+ PRs)'}; pooled sd of ln QU = ${f1(m.logSd, 2)}. Under 9 PRs a type shows min / median / max, not a P80. % uses k, its uncertainty added in.`,
    '',
    '| Type | n | Median QU | P80 QU | Min–max QU | Median % | P80 % |',
    '|---|---|---|---|---|---|---|',
  );
  for (const t of m.types)
    out.push(
      t.n
        ? `| ${t.type} | ${t.n} | ${qu(t.n >= 9 ? t.median : t.rawMedian)} | ${t.n >= 9 ? qu(t.p80) : '–'} | ${qu(t.min)}–${qu(t.max)} | ${pctStr(t.pctMedian)} | ${t.n >= 9 ? pctStr(t.pctP80) : '–'} |`
        : `| ${t.type} | 0 | no PRs | | | | |`,
    );
  out.push('');

  out.push(
    "## Per phase (median share of a PR's QU)",
    '',
    '| Phase | Median | Mean |',
    '|---|---|---|',
  );
  for (const p of m.phaseShare)
    if (p.mean > 0.001)
      out.push(`| ${p.phase} | ${f1(p.median * 100, 0)}% | ${f1(p.mean * 100, 0)}% |`);
  out.push('');

  out.push('## Cost drivers', '', "Spearman rank correlation with a PR's QU:", '');
  for (const d of m.drivers) out.push(`- ${d.what}: ρ = ${f1(d.rho, 2)}`);
  out.push('', 'Most expensive PRs:', '');
  for (const r of m.top)
    out.push(
      `- PR ${r.number} (${r.branch}, ${r.type}): ${qu(r.qu)} QU · ${r.turns} turns · ${r.subagents} subagent runs · ${r.rounds} review rounds`,
    );
  out.push('');

  const o = m.overhead;
  const covered = m.rows.filter((r) => r.qu > 0).length;
  out.push(
    '## Overhead (not in the type medians)',
    '',
    `- Hub (dispatch): ${qu(o.hubQU)} QU over the PR window, ${qu(o.perPR ?? NaN)} QU per merged PR (${covered} PRs).`,
    `- Ad hoc main-checkout sessions: ${qu(o.adhocQU)} QU; other projects: ${qu(o.otherQU)} QU.`,
    `- Lanes with no merged PR in the window: ${
      o.unmerged.length
        ? o.unmerged
            .slice(0, 8)
            .map((u) => `${u.lane} ${qu(u.qu)}`)
            .join(', ')
        : 'none'
    }.`,
    '',
  );

  const rr = m.rounds;
  out.push(
    '## Q1: do review rounds 3–4 find real issues?',
    '',
    `Window = a round's first review marker to the next round, the first local/dev/PR step, or the merge. "Src fixes" = the window has an edit to non-test source. Report verdicts are parsed from archived lane reports (${rr.parsed} lanes readable).`,
    '',
    '| Round | Lanes | Median QU | With src fixes | Median src edits | Report: real bugs | Report: clean |',
    '|---|---|---|---|---|---|---|',
  );
  for (const r of rr.rounds)
    out.push(
      `| ${r.round === 4 ? '4+' : r.round} | ${r.lanes} | ${qu(r.medianQU)} | ${f1(r.srcShare * 100, 0)}% | ${f1(r.medianSrcEdits, 0)} | ${r.reportReal} | ${r.reportClean} |`,
    );
  out.push('');

  const c = m.concurrency;
  out.push(
    '## Q2: more lanes → more merges, or just slowdown?',
    '',
    `Concurrency = lanes with a call in the hour. Over the ${c.days.filter((d) => d.laneHours > 0).length} days with lane work (merge-only days are listed but not correlated): ρ(mean lanes, merged PRs) = ${f1(c.rhoMerged, 2)}; ρ(mean lanes, PRs per lane-hour) = ${f1(c.rhoPerLaneHour, 2)}.`,
    '',
    '| Day | Mean lanes | Max | Lane-hours | Merged | PRs per lane-hour | QU per PR |',
    '|---|---|---|---|---|---|---|',
  );
  for (const d of c.days)
    out.push(
      `| ${d.day} | ${f1(d.meanLanes)} | ${d.maxLanes} | ${d.laneHours} | ${d.merged} | ${f1(d.perLaneHour, 3)} | ${qu(d.quPerPR ?? NaN)} |`,
    );
  out.push('');
  for (const s of c.slowdown)
    out.push(
      `- ${s.cls}: ${f1(s.pctPerLane, 1)}% more wall time per extra working session (n = ${s.n} heavy.sh runs).`,
    );
  out.push('');

  const flags = m.flags.length
    ? m.flags.map((f) => `${f.flag} ${f.calls} calls (${f1(f.quShare * 100, 2)}% of QU)`).join('; ')
    : 'none';
  out.push(
    '## Data quality',
    '',
    `- ${qu(m.totalQU)} QU in the calls table; ${m.dupes} duplicate sightings merged; ${m.orphans} subagent files without their parent session.`,
    `- Price flags: ${flags}.`,
    `- Additivity: ${m.additivity.sessions} sessions in the meter log; median calls-table / status-line cost = ${f1(m.additivity.medianRatio, 2)}; ${m.additivity.outside} outside 0.85–1.10.`,
    `- Phase heuristics agree with explicit \`pnpm board lane\` markers on ${m.agreement.share === null ? '–' : `${f1(m.agreement.share * 100, 0)}%`} of QU (${m.agreement.sessions} sessions).`,
    `- Unattributed: ${m.unattributedShare === null ? '–' : `${f1(m.unattributedShare * 100, 1)}%`} of the QU in PR windows.`,
    '',
  );

  out.push(
    '## PR table',
    '',
    '| PR | Branch | Type | Files | Lines | Rounds | Local / dev runs | Turns | Subagents | QU | Biggest phase |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
  );
  for (const r of m.rows) {
    const big = Object.entries(r.byPhase).sort((x, y) => y[1] - x[1])[0];
    out.push(
      `| ${r.number} | ${r.branch} | ${r.type} | ${r.files} | ${r.lines} | ${r.rounds} | ${r.localRuns} / ${r.devRuns} | ${r.turns} | ${r.subagents} | ${r.qu ? qu(r.qu) : 'no calls'} | ${big ? `${big[0]} ${f1((big[1] / r.qu) * 100, 0)}%` : '–'} |`,
    );
  }
  return out;
}
